#!/usr/bin/env python3
import argparse
import csv
import re
import sys
from collections import OrderedDict


def natural_key(text):
    return [int(part) if part.isdigit() else part for part in re.split(r"(\d+)", text)]


def location_key(location):
    parts = location.rsplit(":", 2)
    if len(parts) == 3 and parts[1].isdigit() and parts[2].isdigit():
        return (parts[0], int(parts[1]), int(parts[2]))
    return (location, 0, 0)


def is_number(text):
    return re.fullmatch(r"[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?", text) is not None


def format_value(value, decimal_comma):
    if decimal_comma and is_number(value):
        return value.replace(".", ",")
    return value


def read_records(path):
    with open(path, newline="") as stream:
        reader = csv.DictReader(stream)
        expected = {"instance", "ticks", "location", "expression", "value"}
        if reader.fieldnames is None or not expected.issubset(reader.fieldnames):
            sys.exit(f"error: '{path}' is not a probe file (expected columns: instance,ticks,location,expression,value)")
        return list(reader)


def build_table(records):
    probes_by_instance = {}
    for record in records:
        probes_by_instance.setdefault(record["instance"], set()).add((record["location"], record["expression"]))

    columns = []
    for instance in sorted(probes_by_instance, key=natural_key):
        probes = sorted(probes_by_instance[instance], key=lambda probe: location_key(probe[0]))
        names = [expression for _, expression in probes]
        for location, expression in probes:
            label = expression if names.count(expression) == 1 else f"{expression} ({location})"
            columns.append((instance, location, expression, label))

    index = {(instance, location, expression): position for position, (instance, location, expression, _) in enumerate(columns)}
    rows = OrderedDict()
    duplicates = 0
    for record in records:
        tick = int(record["ticks"])
        row = rows.setdefault(tick, [""] * len(columns))
        position = index[(record["instance"], record["location"], record["expression"])]
        if row[position] != "":
            duplicates += 1
        row[position] = record["value"]

    return columns, OrderedDict(sorted(rows.items())), duplicates


def write_table(columns, rows, output, delimiter, decimal_comma):
    writer = csv.writer(output, delimiter=delimiter, lineterminator="\n")
    instance_row = ["ticks"]
    previous = None
    for instance, _, _, _ in columns:
        instance_row.append(instance if instance != previous else "")
        previous = instance
    writer.writerow(instance_row)
    writer.writerow([""] + [label for _, _, _, label in columns])
    for tick, values in rows.items():
        writer.writerow([tick] + [format_value(value, decimal_comma) for value in values])


def main():
    parser = argparse.ArgumentParser(description="Turn the csv file written by chips probe statements into one row per tick and one column per probe of each instance.")
    parser.add_argument("input", help="csv file generated by the probe statements")
    parser.add_argument("-o", "--output", help="output csv file (default: standard output)")
    parser.add_argument("-d", "--delimiter", default=",", help="column delimiter of the output, '\\t' for tabs (default: ',')")
    parser.add_argument("--decimal-comma", action="store_true", help="write numbers with a decimal comma (e.g. 0,5)")
    args = parser.parse_args()

    delimiter = "\t" if args.delimiter in ("\\t", "tab") else args.delimiter
    if len(delimiter) != 1:
        sys.exit("error: the delimiter must be a single character")
    if args.decimal_comma and delimiter == ",":
        sys.exit("error: --decimal-comma needs a delimiter other than ','")

    columns, rows, duplicates = build_table(read_records(args.input))
    if duplicates:
        print(f"warning: {duplicates} value(s) probed twice at the same tick by the same probe, the last one is kept", file=sys.stderr)

    if args.output:
        with open(args.output, "w", newline="") as output:
            write_table(columns, rows, output, delimiter, args.decimal_comma)
    else:
        write_table(columns, rows, sys.stdout, delimiter, args.decimal_comma)


if __name__ == "__main__":
    main()
