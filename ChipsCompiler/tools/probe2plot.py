#!/usr/bin/env python3
import argparse
import csv
import math
import os
import re
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


def natural_key(text):
    return [int(part) if part.isdigit() else part for part in re.split(r"(\d+)", text)]


def location_key(location):
    parts = location.rsplit(":", 2)
    if len(parts) == 3 and parts[1].isdigit() and parts[2].isdigit():
        return (parts[0], int(parts[1]), int(parts[2]))
    return (location, 0, 0)


def to_number(text):
    text = text.strip()
    if text in ("true", "false"):
        return 1.0 if text == "true" else 0.0
    try:
        return float(text)
    except ValueError:
        return None


def read_series(path, pattern):
    series = {}
    skipped = 0
    with open(path, newline="") as stream:
        reader = csv.DictReader(stream)
        expected = {"instance", "ticks", "location", "expression", "value"}
        if reader.fieldnames is None or not expected.issubset(reader.fieldnames):
            sys.exit(f"error: '{path}' is not a probe file (expected columns: instance,ticks,location,expression,value)")
        for record in reader:
            if pattern and not pattern.search(record["expression"]):
                continue
            value = to_number(record["value"])
            if value is None:
                skipped += 1
                continue
            probes = series.setdefault(record["instance"], {})
            points = probes.setdefault((record["location"], record["expression"]), ([], []))
            points[0].append(int(record["ticks"]))
            points[1].append(value)
    return series, skipped


def safe_name(text):
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text).strip("_") or "instance"


def plot_instance(instance, probes, columns, width, height):
    keys = sorted(probes, key=lambda probe: location_key(probe[0]))
    names = [expression for _, expression in keys]
    count = len(keys)
    columns = max(1, min(columns, count))
    rows = math.ceil(count / columns)
    figure, axes = plt.subplots(rows, columns, figsize=(width * columns, height * rows), sharex=True, squeeze=False)
    for position, key in enumerate(keys):
        location, expression = key
        axis = axes[position // columns][position % columns]
        ticks, values = probes[key]
        order = sorted(range(len(ticks)), key=ticks.__getitem__)
        ticks = [ticks[i] for i in order]
        values = [values[i] for i in order]
        axis.plot(ticks, values, drawstyle="steps-post", marker="." if len(ticks) <= 200 else None, linewidth=1)
        title = expression if names.count(expression) == 1 else f"{expression} ({location})"
        axis.set_title(title, fontsize=9)
        axis.grid(True, alpha=0.3)
    for position in range(count, rows * columns):
        axes[position // columns][position % columns].set_visible(False)
    for column in range(columns):
        axes[rows - 1][column].set_xlabel("ticks")
    figure.suptitle(instance)
    figure.tight_layout()
    return figure


def main():
    parser = argparse.ArgumentParser(description="Plot the values written by chips probe statements, one figure per instance and one curve per probe.")
    parser.add_argument("input", help="csv file generated by the probe statements")
    parser.add_argument("-o", "--output", default=".", help="output folder, or a .pdf file to get every figure in one document (default: current folder)")
    parser.add_argument("-f", "--format", default="png", choices=["png", "svg", "pdf"], help="image format when --output is a folder (default: png)")
    parser.add_argument("-p", "--probes", help="regular expression: only plot the probed expressions matching it")
    parser.add_argument("-i", "--instances", help="regular expression: only plot the instances matching it")
    parser.add_argument("-c", "--columns", type=int, default=2, help="number of subplots per row (default: 2)")
    parser.add_argument("--size", type=float, nargs=2, default=(6.0, 3.0), metavar=("W", "H"), help="size of one subplot in inches (default: 6 3)")
    args = parser.parse_args()

    probe_pattern = re.compile(args.probes) if args.probes else None
    instance_pattern = re.compile(args.instances) if args.instances else None

    series, skipped = read_series(args.input, probe_pattern)
    if skipped:
        print(f"warning: {skipped} non numeric value(s) ignored", file=sys.stderr)
    instances = [instance for instance in sorted(series, key=natural_key) if not instance_pattern or instance_pattern.search(instance)]
    if not instances:
        print("warning: nothing to plot", file=sys.stderr)
        return

    single_pdf = args.output.lower().endswith(".pdf")
    if single_pdf:
        from matplotlib.backends.backend_pdf import PdfPages
        parent = os.path.dirname(args.output)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with PdfPages(args.output) as document:
            for instance in instances:
                figure = plot_instance(instance, series[instance], args.columns, *args.size)
                document.savefig(figure)
                plt.close(figure)
        print(args.output)
    else:
        os.makedirs(args.output, exist_ok=True)
        for instance in instances:
            figure = plot_instance(instance, series[instance], args.columns, *args.size)
            path = os.path.join(args.output, f"{safe_name(instance)}.{args.format}")
            figure.savefig(path, dpi=120)
            plt.close(figure)
            print(path)


if __name__ == "__main__":
    main()